import { posix, relative, sep } from 'node:path'
import type { AnalysisResult, AnalyzedTool } from '../analyzer/model'
import type { ResolvedConfig } from '../analyzer/config'
import { DIAGNOSTIC_RULES, type DiagnosticCode } from '../analyzer/diagnostics'
import type { ConfirmPolicy, RouteEntry, ToolAdapter, ToolAnnotations } from '../core/types'

export const MANIFEST_VERSION = 1
export const GENERATED_HEADER = '// @generated by actionmcp. Do not edit.'

export interface ManifestTool {
  name: string
  kind: AnalyzedTool['kind']
  description: string
  source: AnalyzedTool['source']
  schemaSource: AnalyzedTool['schemaSource']
  annotations: ToolAnnotations
  confirm: ConfirmPolicy
  adapter?: ToolAdapter
  validated: boolean
  diagnostics: string[]
}

export interface Manifest {
  version: typeof MANIFEST_VERSION
  nextVersion: string
  tools: ManifestTool[]
  routes: RouteEntry[]
}

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/
const IMPORTABLE_EXTENSION = /\.(?:tsx?|jsx?)$/

export function renderRegistry(analysis: AnalysisResult, config: ResolvedConfig): string {
  const tools = analysis.tools.filter(isRegistrable)
  const modules = [...new Set(tools.map((tool) => tool.source.file))].toSorted()
  const moduleName = (tool: AnalyzedTool) => `m${modules.indexOf(tool.source.file)}`
  const reference = (tool: AnalyzedTool) => `${moduleName(tool)}${accessor(tool.source.export)}`
  const agentTools = tools.filter((tool) => tool.kind === 'agent')
  const jsdocTools = tools.filter((tool) => tool.kind === 'jsdoc')

  const lines = [GENERATED_HEADER, "import 'server-only'", "import { createRegistry } from 'actionmcp/server'"]
  modules.forEach((file, index) => lines.push(`import * as m${index} from ${quote(importPath(config, file))}`))
  if (analysis.registry) lines.push(`import explicit from ${quote(importPath(config, analysis.registry))}`)
  lines.push('', 'export default createRegistry({')
  if (agentTools.length > 0) {
    lines.push('  agent: {', ...agentTools.map((tool) => `    ${key(tool.name)}: ${reference(tool)},`), '  },')
  }
  if (jsdocTools.length > 0) {
    lines.push('  jsdoc: {', ...jsdocTools.flatMap((tool) => renderJsdocTool(tool, reference(tool))), '  },')
  }
  if (analysis.registry) lines.push('  explicit,')
  lines.push(`  routes: ${indent(JSON.stringify(analysis.routes, null, 2), 2)},`, '})', '')
  return lines.join('\n')
}

export function renderManifest(analysis: AnalysisResult, nextVersion: string): string {
  const manifest: Manifest = {
    version: MANIFEST_VERSION,
    nextVersion,
    tools: analysis.tools.map(toManifestTool),
    routes: analysis.routes,
  }
  return `${JSON.stringify(manifest, null, 2)}\n`
}

function toManifestTool(tool: AnalyzedTool): ManifestTool {
  return {
    name: tool.name,
    kind: tool.kind,
    description: tool.description,
    source: tool.source,
    schemaSource: tool.schemaSource,
    annotations: tool.annotations,
    confirm: tool.confirm,
    ...(tool.adapter ? { adapter: tool.adapter } : {}),
    validated: tool.validated,
    diagnostics: tool.diagnostics.toSorted(),
  }
}

function isRegistrable(tool: AnalyzedTool): boolean {
  if (tool.kind !== 'agent' && tool.kind !== 'jsdoc') return false
  return !tool.diagnostics.some((code) => DIAGNOSTIC_RULES[code as DiagnosticCode]?.level === 'error')
}

function renderJsdocTool(tool: AnalyzedTool, reference: string): string[] {
  const { readOnlyHint, consequentialHint, untrustedContentHint } = tool.annotations
  const entry = {
    description: tool.description,
    ...(tool.inputSchema ? { inputSchema: tool.inputSchema } : {}),
    annotations: { readOnlyHint, consequentialHint, untrustedContentHint },
    ...(tool.adapter ? { adapter: tool.adapter } : {}),
    validated: false,
  }
  const body = Object.entries(entry).map(([name, value]) => `      ${name}: ${indent(JSON.stringify(value, null, 2), 6)},`)
  return [`    ${key(tool.name)}: {`, `      action: ${reference},`, ...body, '    },']
}

function importPath(config: ResolvedConfig, file: string): string {
  const target = relative(config.outDir, posix.join(config.cwd.split(sep).join('/'), file)).split(sep).join('/')
  const path = target.replace(IMPORTABLE_EXTENSION, '')
  return path.startsWith('.') ? path : `./${path}`
}

function accessor(exportName: string): string {
  return IDENTIFIER.test(exportName) ? `.${exportName}` : `[${quote(exportName)}]`
}

function key(name: string): string {
  return IDENTIFIER.test(name) ? name : quote(name)
}

function quote(value: string): string {
  return JSON.stringify(value)
}

function indent(text: string, spaces: number): string {
  return text.split('\n').join(`\n${' '.repeat(spaces)}`)
}
