import { readFileSync, statSync } from 'node:fs'
import { join } from 'node:path'
import { afterEach, describe, expect, it } from 'vitest'
import { createProject, type TemporaryProject } from '../analyzer/__fixtures__/project'
import { resolveConfig } from '../analyzer/config'
import { generate, readNextVersion } from './index'

const TSCONFIG = JSON.stringify({ compilerOptions: { strict: true, target: 'es2022', module: 'esnext', moduleResolution: 'bundler' } })
const PAGE = 'export default function Page() { return null }\n'

const FILES = {
  'tsconfig.json': TSCONFIG,
  'app/page.tsx': PAGE,
  'app/projects/[id]/page.tsx': PAGE,
  'app/todos/actions.ts': `'use server'
import { agent } from 'actionmcp/server'
import { z } from 'zod'

export const addTodo = agent(
  { description: 'Add an item to the todo list. Returns the created item.', input: z.object({ text: z.string() }) },
  async ({ text }) => {
    await requireUser()
    return { text }
  },
)

export const listTodos = agent({ description: 'List the todos of the signed-in user.', readOnly: true, name: 'todos.list' }, async () => {
  await requireUser()
  return []
})
`,
  'app/projects/actions.ts': `'use server'

/**
 * Rename the current project. It says "hello" and returns the new name.
 * @agent consequential
 */
export async function renameProject(input: { projectId: string; name: string }) {
  await requireUser()
  return schema.parse(input)
}

/**
 * Import projects from an uploaded form and return the count.
 * @agent formdata
 */
export async function importProjects(previous: unknown, formData: FormData) {
  await requireUser()
  return schema.parse(formData)
}
`,
  'agent-tools.ts': `import { defineAgentTools, tool, fromSafeAction } from 'actionmcp/server'
import { loginUser } from './app/auth'
import { loginSchema } from './lib/schemas'
export default defineAgentTools({
  loginUser: tool(fromSafeAction(loginUser), { description: 'Sign in with a username and a password.', input: loginSchema }),
})
`,
}

let project: TemporaryProject | undefined

afterEach(() => {
  project?.remove()
  project = undefined
})

function read(file: string): string {
  if (!project) throw new Error('No project')
  return readFileSync(join(project.cwd, '.agent-tools', file), 'utf8')
}

describe('generate', () => {
  it('writes the registry', async () => {
    project = createProject(FILES)
    const result = await generate(resolveConfig({ jsdoc: true }, project.cwd))
    expect(result.written).toEqual(['registry.ts', 'manifest.json'])
    expect(read('registry.ts')).toMatchInlineSnapshot(`
      "// @generated by actionmcp. Do not edit.
      import 'server-only'
      import { createRegistry } from 'actionmcp/server'
      import * as m0 from "../app/projects/actions"
      import * as m1 from "../app/todos/actions"
      import explicit from "../agent-tools"

      export default createRegistry({
        agent: {
          addTodo: m1.addTodo,
          "todos.list": m1.listTodos,
        },
        jsdoc: {
          importProjects: {
            action: m0.importProjects,
            description: "Import projects from an uploaded form and return the count.",
            annotations: {
              "readOnlyHint": false,
              "consequentialHint": true,
              "untrustedContentHint": false
            },
            adapter: "formdata",
            validated: false,
          },
          renameProject: {
            action: m0.renameProject,
            description: "Rename the current project. It says \\"hello\\" and returns the new name.",
            inputSchema: {
              "type": "object",
              "properties": {
                "projectId": {
                  "type": "string"
                },
                "name": {
                  "type": "string"
                }
              },
              "required": [
                "projectId",
                "name"
              ]
            },
            annotations: {
              "readOnlyHint": false,
              "consequentialHint": true,
              "untrustedContentHint": false
            },
            validated: false,
          },
        },
        explicit,
        routes: [
          {
            "pattern": "/",
            "params": []
          },
          {
            "pattern": "/projects/[id]",
            "params": [
              "id"
            ]
          }
        ],
      })
      "
    `)
  })

  it('writes the manifest', async () => {
    project = createProject(FILES)
    await generate(resolveConfig({ jsdoc: true }, project.cwd))
    const manifest = JSON.parse(read('manifest.json')) as { version: number; nextVersion: string; tools: Array<Record<string, unknown>>; routes: unknown[] }
    expect(manifest.version).toBe(1)
    expect(manifest.nextVersion).toMatch(/^(?:\d+\.\d+\.\d+.*|unknown)$/)
    expect(manifest).not.toHaveProperty('generatedAt')
    expect(manifest.routes).toHaveLength(2)
    expect(manifest.tools).toEqual([
      {
        name: 'addTodo',
        kind: 'agent',
        description: 'Add an item to the todo list. Returns the created item.',
        source: { file: 'app/todos/actions.ts', export: 'addTodo', line: 5 },
        schemaSource: 'standard-schema',
        annotations: { readOnlyHint: false, consequentialHint: true, untrustedContentHint: false },
        confirm: 'consequential',
        validated: true,
        diagnostics: [],
      },
      expect.objectContaining({ name: 'importProjects', kind: 'jsdoc', adapter: 'formdata', schemaSource: 'none', validated: false, diagnostics: ['AT101'] }),
      expect.objectContaining({ name: 'loginUser', kind: 'explicit', adapter: 'safe-action', validated: false }),
      expect.objectContaining({ name: 'renameProject', kind: 'jsdoc', schemaSource: 'typescript' }),
      expect.objectContaining({ name: 'todos.list', kind: 'agent', annotations: { readOnlyHint: true, consequentialHint: false, untrustedContentHint: false } }),
    ])
  })

  it('produces identical bytes on a second run and does not rewrite the files', async () => {
    project = createProject(FILES)
    const config = resolveConfig({ jsdoc: true }, project.cwd)
    await generate(config)
    const first = { registry: read('registry.ts'), manifest: read('manifest.json') }
    const modified = statSync(join(project.cwd, '.agent-tools/registry.ts')).mtimeMs
    const second = await generate(config)
    expect(second.written).toEqual([])
    expect({ registry: read('registry.ts'), manifest: read('manifest.json') }).toEqual(first)
    expect(statSync(join(project.cwd, '.agent-tools/registry.ts')).mtimeMs).toBe(modified)
  })

  it('leaves tools with errors out of the registry and keeps them in the manifest', async () => {
    project = createProject({
      'app/actions.ts': `'use server'
import { agent } from 'actionmcp/server'
export const good = agent({ description: 'Do something useful for the signed-in user.' }, async () => { await requireUser() })
export const bad = agent({ description: text }, async () => { await requireUser() })
`,
    })
    const result = await generate(resolveConfig({}, project.cwd))
    expect(result.analysis.diagnostics.map((diagnostic) => diagnostic.code)).toEqual(['AT005'])
    expect(read('registry.ts')).toContain('good: m0.good')
    expect(read('registry.ts')).not.toContain('m0.bad')
    expect(read('manifest.json')).toContain('"name": "bad"')
  })

  it('writes an empty registry for a project without tools', async () => {
    project = createProject({ 'lib/x.ts': 'export const x = 1\n' })
    await generate(resolveConfig({ outDir: 'generated/tools' }, project.cwd))
    expect(readFileSync(join(project.cwd, 'generated/tools/registry.ts'), 'utf8')).toBe(
      "// @generated by actionmcp. Do not edit.\nimport 'server-only'\nimport { createRegistry } from 'actionmcp/server'\n\nexport default createRegistry({\n  routes: [],\n})\n",
    )
  })

  it('imports modules relative to a nested output folder and quotes unusual export names', async () => {
    project = createProject({
      'app/actions.ts': `'use server'\nimport { agent } from 'actionmcp/server'\nexport default agent({ description: 'Do something useful for the signed-in user.', name: 'run' }, async () => { await requireUser() })\n`,
    })
    await generate(resolveConfig({ outDir: 'generated/tools' }, project.cwd))
    const registry = readFileSync(join(project.cwd, 'generated/tools/registry.ts'), 'utf8')
    expect(registry).toContain('import * as m0 from "../../app/actions"')
    expect(registry).toContain('run: m0.default,')
  })
})

describe('readNextVersion', () => {
  it('reads the installed Next.js version', () => {
    expect(readNextVersion(process.cwd())).toMatch(/^16\./)
  })

  it('returns unknown when the package cannot be read', () => {
    project = createProject({ 'node_modules/next/package.json': 'not json' })
    expect(readNextVersion(project.cwd)).toBe('unknown')
  })
})
